SENTENCE_END = ".!?:\"”’)…"


def join_broken_paragraphs(text: str) -> str:
    """Слепва абзац, прекъснат по средата на изречение (разделител на страница в PDF)."""
    paragraphs = re.split(r"\n\s*\n", text)
    merged: list[str] = []
    for paragraph in paragraphs:
        current = paragraph.strip()
        if not current:
            continue
        previous = merged[-1] if merged else ""
        if previous and previous[-1] not in SENTENCE_END and current[0].islower():
            merged[-1] = previous + " " + current
        else:
            merged.append(current)
    return "\n\n".join(merged)


PARAGRAPH_END = (".", "!", "?", "”", '"', "’", ")", "…")
NON_PROSE_LINE_RE = re.compile(r"^(\d{1,2}\.|[A-D]\)|Task\b|Read the text|Directions)")


def restore_reading_paragraphs(text: str) -> str:
    """Вмъква празен ред след последния ред на абзац в текстовете за четене.

    Редовете на PDF-а са запазени в данните. Ред, който завършва с край на изречение и е
    значително по-къс от най-дългия ред в раздела, а следващият ред започва с главна буква
    и не е въпрос/опция, се приема за край на абзац.
    """
    # Същите заглавия, по които lib/english-mock.ts реже разделите.
    start_match = re.search(r"(?m)^\s*(?:PART\s+\w+:\s*)?READING COMPREHENSION\s*$", text)
    if not start_match:
        return text
    start = start_match.start()
    end_match = re.search(r"(?m)^\s*(?:PART\s+\w+:\s*WRITING|WRITING)\s*$", text[start:])
    if not end_match:
        return text
    end = start + end_match.start()
    lines = text[start:end].split("\n")
    max_len = max((len(line.rstrip()) for line in lines if line.strip()), default=0)
    out: list[str] = []
    for i, line in enumerate(lines):
        out.append(line)
        current = line.rstrip()
        following = lines[i + 1].strip() if i + 1 < len(lines) else ""
        if (
            current
            and following
            and current.endswith(PARAGRAPH_END)
            and len(current) < 0.78 * max_len
            and following[0].isupper()
            and not NON_PROSE_LINE_RE.match(current)
            and not NON_PROSE_LINE_RE.match(following)
        ):
            out.append("")
    return text[:start] + "\n".join(out) + text[end:]


def process_english(data: dict) -> None:
    for exam in data["exams"]:
        if not exam["id"].endswith("_b2"):
            continue
        exam["context_text"] = restore_reading_paragraphs(join_broken_paragraphs(exam.get("context_text") or ""))
        for q in exam["questions"]:
            if exam["id"] == "dzi_english_2023_may_b2" and 26 <= q["number"] <= 30:
                if q.get("options") == {"B": "False"}:
                    q["options"] = {"A": "True", "B": "False"}
            if exam["id"] == "dzi_english_2025_may_b2" and 21 <= q["number"] <= 25:
                # Task Five от Listening е маркирана като reading в суровите данни.
                if q.get("section") == "reading":
                    q["section"] = "listening"


