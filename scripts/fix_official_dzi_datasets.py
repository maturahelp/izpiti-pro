def dump(path: Path, data) -> None:
    # Запазваме оформлението на файла (2 интервала, без \uXXXX, без нов ред в края),
    # за да е четим diff-ът.
    trailing = "\n" if path.read_text(encoding="utf-8").endswith("\n") else ""
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + trailing, encoding="utf-8")


