LATIN_TO_CYRILLIC = str.maketrans(
    {
        "a": "а", "e": "е", "o": "о", "p": "р", "c": "с", "x": "х", "y": "у",
        "A": "А", "B": "В", "E": "Е", "K": "К", "M": "М", "H": "Н", "O": "О",
        "P": "Р", "C": "С", "T": "Т", "X": "Х",
    }
)
CYRILLIC_RE = re.compile(r"[А-Яа-яЁёѝЍ]")
LATIN_RE = re.compile(r"[A-Za-z]")

BOILERPLATE_TAIL_RE = re.compile(
    r"\s*ДЪРЖАВЕН ЗРЕЛОСТЕН ИЗПИТ ПО БЪЛГАРСКИ ЕЗИК И ЛИТЕРАТУРА"
    r"(?:\s*ЧАСТ\s*3\s*\(Време за работа:\s*120 минути\)\s*"
    r"Аргументативния текст напишете в листа за отговори на предвиденото място\.|\s*отговори\.)?\s*$"
)


def fix_latin_in_cyrillic(text: str) -> str:
    """Заменя латинските омоглифи само в думи, които съдържат и кирилица."""

    def fix_word(match: re.Match) -> str:
        word = match.group(0)
        if CYRILLIC_RE.search(word) and LATIN_RE.search(word):
            return word.translate(LATIN_TO_CYRILLIC)
        return word

    return re.sub(r"\S+", fix_word, text)


def clean_common(text: str) -> str:
    """Нормализира текст преди реконструкция; маха и маркерите от предишно пускане,
    така че скриптът да е идемпотентен."""
    if not text:
        return text
    text = re.sub(r"\s+", " ", text.replace("__", ""))
    text = fix_latin_in_cyrillic(text)
    text = re.sub(r"\b(по|най|По|Най)-\s+(?=\S)", r"\1-", text)
    text = BOILERPLATE_TAIL_RE.sub("", text)
    return text.strip()


def nospace(text: str) -> str:
    return re.sub(r"\s+", "", text).replace("¹", "1")


def same_chars(a: str, b: str, label: str) -> None:
    ca, cb = Counter(nospace(a)), Counter(nospace(b))
    if ca != cb:
        missing = "".join((cb - ca).elements())
        extra = "".join((ca - cb).elements())
        raise SystemExit(f"[{label}] реконструкцията не съвпада с оригинала: липсва {missing!r}, в повече {extra!r}")


def rebuild(original: str, items: list[dict], label: str, replacements=(), append=()) -> str:
    """Пренарежда текста на задача по списък от части, без да губи знаци.

    Част с ключ ``p`` е абзац и се взема дословно от оригинала – от началото ѝ до началото
    на следващата част. Част с ключ ``lines`` е стихотворен блок: редовете се записват така,
    както са подадени (с "" за празен ред между строфи), а ``cite`` е източникът след тях.
    Част с ``drop`` се изрязва (например бележка под линия, попаднала насред текста).
    ``start`` задава изрично откъде започва частта, когато първият ѝ ред се среща и по-рано.
    """
    text = original
    for old, new in replacements:
        if old not in text:
            if new in text:
                continue  # вече приложено при предишно пускане
            raise SystemExit(f"[{label}] не намирам {old!r} за замяна")
        text = text.replace(old, new)

    positions = []
    cursor = 0
    for item in items:
        key = item.get("start") or (item["p"] if "p" in item else next(line for line in item["lines"] if line))
        idx = text.find(key, cursor)
        if idx < 0:
            raise SystemExit(f"[{label}] не намирам началото {key!r}")
        positions.append(idx)
        cursor = idx + len(key)
    if positions[0] != 0:
        raise SystemExit(f"[{label}] първата част не започва от началото на текста")

    out: list[str] = []
    kept: list[str] = []
    for i, item in enumerate(items):
        end = positions[i + 1] if i + 1 < len(items) else len(text)
        segment = text[positions[i]:end].strip()
        if item.get("drop"):
            continue
        kept.append(segment)
        if "lines" in item:
            body = "\n".join(item["lines"])
            if item.get("cite"):
                body += "\n" + item["cite"]
            same_chars(body, segment, f"{label} / {item['lines'][0][:30]}")
            out.append(body)
        else:
            out.append(re.sub(r"\s+", " ", segment))
    out.extend(append)
    result = "\n\n".join(out)
    same_chars(result, "".join(kept) + "".join(append), label)
    return result


def paragraphize(text: str, starts: list[str], label: str) -> str:
    """Вмъква празен ред пред всяко от посочените начала на абзац (всяко трябва да е уникално)."""
    for start in starts:
        if text.count(start) != 1:
            raise SystemExit(f"[{label}] началото на абзац {start!r} се среща {text.count(start)} пъти")
        text = text.replace(start, "\n\n" + start)
    return re.sub(r"[ \t]+\n", "\n", re.sub(r"\n{3,}", "\n\n", text)).strip()


def underline(text: str, fragment: str, label: str) -> str:
    if text.count(fragment) != 1:
        raise SystemExit(f"[{label}] подчертаният фрагмент {fragment!r} се среща {text.count(fragment)} пъти")
    return text.replace(fragment, f"__{fragment}__")


def replace_diagram_tail(ctx: str, replacement: str, label: str) -> str:
    marker = "ТЕКСТ 2 (ДИАГРАМА)"
    idx = ctx.find(marker)
    if idx < 0:
        raise SystemExit(f"[{label}] няма маркер {marker!r}")
    head = ctx[:idx].rstrip()
    return head + "\n\n" + marker + ("\n\n" + replacement if replacement else "")


def mark_texts(ctx: str) -> str:
    ctx = re.sub(r"\s*ТЕКСТ 1\s*", "\n\nТЕКСТ 1\n\n", ctx, count=1)
    ctx = re.sub(r"\s*ТЕКСТ 2(?! \(ДИАГРАМА\))\s*", "\n\nТЕКСТ 2\n\n", ctx, count=1)
    return ctx.strip()


def build_pairs(question: dict, label: str) -> dict[str, str]:
    """Задача 39: от опциите „„Заглавие“ 1. Автор“ и ключа „А) 3 Б) 1 В) 2“ прави {заглавие: автор}."""
    options = question.get("options") or {}
    titles: dict[str, str] = {}
    authors: dict[str, str] = {}
    for letter, raw in options.items():
        match = re.match(r"^\s*(„[^“]+“)\s*(\d)\.\s*(.+?)\s*$", raw)
        if not match:
            raise SystemExit(f"[{label}] неочаквана опция в задача 39: {raw!r}")
        titles[letter] = match.group(1)
        authors[match.group(2)] = match.group(3)
    key = dict(re.findall(r"([АБВГ])\)\s*(\d)", question.get("official_answer") or ""))
    if set(key) != set(titles):
        raise SystemExit(f"[{label}] ключът на задача 39 не покрива опциите: {key} / {list(titles)}")
    return {titles[letter]: authors[number] for letter, number in key.items()}


