def split_task_13(question: str, label: str) -> tuple[str, str]:
    marker = "Прочетете двата текста и изпълнете задачите към тях"
    idx = question.find(marker)
    if idx < 0:
        raise SystemExit(f"[{label}] задача 13 не съдържа залепените текстове")
    return question[:idx].strip(), question[idx:].strip()


