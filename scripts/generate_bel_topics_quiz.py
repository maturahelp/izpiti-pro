def read_titles() -> list[str]:
    text = THEORY_TS.read_text(encoding="utf-8")
    return re.findall(r"^    title: '(.*)',$", text, flags=re.M)


def validate(titles: list[str]) -> None:
    expected = sum(count for _, count in SECTIONS)
    assert len(titles) == expected, f"{len(titles)} теми в теорията, очаквани {expected}"
    assert len(QUESTIONS) == expected, f"{len(QUESTIONS)} групи въпроси, очаквани {expected}"
    for index, (title, questions) in enumerate(zip(titles, QUESTIONS)):
        assert len(questions) == 10, f"[{index}] {title}: {len(questions)} въпроса"
        for number, q in enumerate(questions, 1):
            options = [q["correct"], *q["wrong"]]
            where = f"[{index}] {title} / въпрос {number}"
            assert len(q["wrong"]) == 3, f"{where}: нужни са 3 грешни отговора"
            assert len(set(options)) == 4, f"{where}: повтарящи се отговори"
            assert all(option.strip() for option in options), f"{where}: празен отговор"
            assert q["text"].strip() and q["explanation"].strip(), f"{where}: липсва условие или обяснение"


def build_dataset() -> dict:
    titles = read_titles()
    validate(titles)

    sections = []
    cursor = 0
    for section_title, count in SECTIONS:
        topics = []
        for title, questions in zip(titles[cursor:cursor + count], QUESTIONS[cursor:cursor + count]):
            topics.append({
                "title": title,
                "question_count": len(questions),
                "questions": [
                    {
                        "number": number,
                        "type": "multiple_choice",
                        "text": q["text"],
                        "options": [q["correct"], *q["wrong"]],
                        "correct_index": 0,
                        "correct_answer": q["correct"],
                        "explanation": q["explanation"],
                    }
                    for number, q in enumerate(questions, 1)
                ],
            })
        sections.append({"title": section_title, "topics": topics})
        cursor += count

    return {
        "title": "Български език – тестове към правилата (ДЗИ)",
        "topic_count": len(titles),
        "question_count": sum(len(group) for group in QUESTIONS),
        "sections": sections,
    }


def main() -> None:
    dataset = build_dataset()
    OUTPUT_JSON.write_text(json.dumps(dataset, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Generated {dataset['question_count']} questions in {OUTPUT_JSON.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
