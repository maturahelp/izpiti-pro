export type Nvo4MaterialItemType = 'theory' | 'worked_example' | 'practice' | 'quick_check' | 'exam_tip'

export type Nvo4MaterialItem = {
  id: string
  type: Nvo4MaterialItemType
  title: string
  body: string
  prompts?: string[]
}

export type Nvo4MaterialLesson = {
  id: string
  title: string
  goal: string
  items: Nvo4MaterialItem[]
}

export type Nvo4MaterialUnit = {
  id: string
  title: string
  description: string
  lessons: Nvo4MaterialLesson[]
}

export type Nvo4MaterialTree = {
  subject: 'bel' | 'math'
  title: string
  description: string
  units: Nvo4MaterialUnit[]
}

type LessonBlueprint = {
  title: string
  focus: string
  practice: string
  check: string
  tip: string
}

type UnitBlueprint = {
  title: string
  description: string
  lessons: LessonBlueprint[]
}

function slugify(value: string) {
  return value
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, '-')
    .replace(/^-+|-+$/g, '')
}

function buildLesson(subject: 'bel' | 'math', unitIndex: number, lessonIndex: number, lesson: LessonBlueprint): Nvo4MaterialLesson {
  const baseId = `nvo4-${subject}-${unitIndex + 1}-${lessonIndex + 1}-${slugify(lesson.title)}`
  return {
    id: baseId,
    title: lesson.title,
    goal: lesson.focus,
    items: [
      {
        id: `${baseId}-theory`,
        type: 'theory',
        title: 'Кратко обяснение',
        body: lesson.focus,
      },
      {
        id: `${baseId}-example`,
        type: 'worked_example',
        title: 'Разгледай пример',
        body: `Първо открий какво се пита, после запиши данните в удобен ред. ${lesson.practice}`,
      },
      {
        id: `${baseId}-practice-a`,
        type: 'practice',
        title: 'Упражнение 1',
        body: lesson.practice,
        prompts: [
          'Запиши данните с кратки означения.',
          'Реши задачата на отделни стъпки.',
          'Провери дали отговорът отговаря точно на въпроса.',
        ],
      },
      {
        id: `${baseId}-practice-b`,
        type: 'practice',
        title: 'Упражнение 2',
        body: lesson.check,
        prompts: [
          'Сравни възможните отговори.',
          'Зачеркни явно грешните варианти.',
          'Обясни защо избраният отговор е най-подходящ.',
        ],
      },
      {
        id: `${baseId}-tip`,
        type: 'exam_tip',
        title: 'Съвет за НВО',
        body: lesson.tip,
      },
    ],
  }
}

function buildTree(subject: 'bel' | 'math', title: string, description: string, units: UnitBlueprint[]): Nvo4MaterialTree {
  return {
    subject,
    title,
    description,
    units: units.map((unit, unitIndex) => ({
      id: `nvo4-${subject}-unit-${unitIndex + 1}-${slugify(unit.title)}`,
      title: unit.title,
      description: unit.description,
      lessons: unit.lessons.map((lesson, lessonIndex) => buildLesson(subject, unitIndex, lessonIndex, lesson)),
    })),
  }
}

