export function buildDziEssaySearchText(material: DziEssayMaterial): string {
  const sectionText = material.sections
    .map((section) => [
      section.title,
      section.lead,
      ...(section.paragraphs ?? []),
      ...(section.bullets ?? []),
      ...(section.numbered ?? []),
      ...(section.table?.headers ?? []),
      ...(section.table?.rows.flat() ?? []),
      ...(section.examples?.flatMap((example) => [
        example.label,
        example.text,
        example.before,
        example.after,
      ]) ?? []),
      section.task?.title,
      section.task?.prompt,
      ...(section.task?.checklist ?? []),
    ].filter(Boolean).join(' '))
    .join(' ')

  return [
    material.group,
    material.title,
    material.description,
    material.keywords.join(' '),
    material.quiz
      .flatMap((question) => [
        question.prompt,
        ...question.options,
        question.explanation,
      ])
      .join(' '),
    sectionText,
  ].join(' ').toLowerCase()
}
